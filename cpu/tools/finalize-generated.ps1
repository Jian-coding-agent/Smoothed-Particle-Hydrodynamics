<#
.SYNOPSIS
    Finalize a CMake-generated Visual Studio build directory:
      1) remove the ALL_BUILD / ZERO_CHECK helper projects;
      2) rewrite absolute paths inside the generated .vcxproj / .filters / .user
         into paths relative to the project directory.

.DESCRIPTION
    Why this is needed:

      * CMake's VS generator always emits an ALL_BUILD project; there is no
        switch to disable it (ZERO_CHECK is disabled through
        CMAKE_SUPPRESS_REGENERATION in CMakeLists.txt).
      * CMake writes absolute paths for OutDir, ImportLibrary,
        ProgramDataBaseFile and the source file reference. Those make the
        generated project unusable if the tree is moved.

    After this script the .sln contains only the real targets and the project
    files reference sources/outputs relatively, e.g.:

        <OutDir>Release\</OutDir>
        <ClCompile Include="..\1.cpp" />

    Only files describing the project are touched. CMake's own bookkeeping
    (CMakeCache.txt, CMakeFiles\*) keeps absolute paths by design - it is the
    build-system state, and it is regenerated by `cmake ..` after moving.

    Re-run this script after every `cmake ..`; build.bat / build.ps1 do it
    automatically. Idempotent.

.PARAMETER Sln
    Path to the generated .sln (its folder is treated as the build directory).

.EXAMPLE
    .\finalize-generated.ps1 -Sln ..\build\SPH.sln

.NOTES
    ASCII-only on purpose: Windows PowerShell 5.1 reads .ps1 as ANSI unless
    the file has a UTF-8 BOM.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Sln
)

$ErrorActionPreference = 'Stop'

$slnPath = (Resolve-Path -LiteralPath $Sln).Path
$buildDir = Split-Path -Parent $slnPath
$helperNames = @('ALL_BUILD', 'ZERO_CHECK')

Write-Host "[finalize] solution: $slnPath"

# ===========================================================================
# 1. remove ALL_BUILD / ZERO_CHECK from the .sln
# ===========================================================================
$text = [System.IO.File]::ReadAllText($slnPath, [System.Text.Encoding]::UTF8)
$lines = $text -split "\r\n|\n"

$removedProjects = New-Object System.Collections.Generic.List[string]
$removedGuids = New-Object System.Collections.Generic.List[string]
$out = New-Object System.Collections.Generic.List[string]

for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = $lines[$i]
    $m = [regex]::Match($line, '^Project\("\{[^}]+\}"\)\s*=\s*"([^"]+)"\s*,\s*"[^"]+"\s*,\s*"(\{[^}]+\})"')
    if ($m.Success -and ($helperNames -contains $m.Groups[1].Value)) {
        $removedProjects.Add($m.Groups[1].Value)
        $removedGuids.Add($m.Groups[2].Value)
        while (($i + 1) -lt $lines.Count -and $lines[$i + 1].Trim() -ne 'EndProject') { $i++ }
        $i++
        continue
    }
    $out.Add($line)
}

if ($removedGuids.Count -gt 0) {
    $filtered = New-Object System.Collections.Generic.List[string]
    foreach ($line in $out) {
        $hit = $false
        foreach ($g in $removedGuids) {
            if ($line.Contains($g)) { $hit = $true; break }
        }
        if (-not $hit) { $filtered.Add($line) }
    }
    $out = $filtered
}

# drop ProjectDependencies sections left empty
$final = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $out.Count; $i++) {
    $line = $out[$i]
    if ($line.Trim() -match '^ProjectSection\(ProjectDependencies\)\s*=\s*postProject$') {
        $j = $i + 1
        while ($j -lt $out.Count -and $out[$j].Trim() -eq '') { $j++ }
        if ($j -lt $out.Count -and $out[$j].Trim() -eq 'EndProjectSection') {
            $i = $j
            continue
        }
    }
    $final.Add($line)
}

# drop GlobalSection blocks left empty
$clean = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $final.Count; $i++) {
    $line = $final[$i]
    if ($line.Trim() -match '^GlobalSection\((.+)\)\s*=') {
        $j = $i + 1
        $hasContent = $false
        while ($j -lt $final.Count -and $final[$j].Trim() -ne 'EndGlobalSection') {
            if ($final[$j].Trim() -ne '') { $hasContent = $true }
            $j++
        }
        if (-not $hasContent -and $j -lt $final.Count) {
            $i = $j
            continue
        }
    }
    $clean.Add($line)
}
$final = $clean

[System.IO.File]::WriteAllText($slnPath, ($final -join "`r`n"), (New-Object System.Text.UTF8Encoding($true)))

if ($removedProjects.Count -gt 0) {
    Write-Host "[finalize] removed from .sln: $($removedProjects -join ', ')" -ForegroundColor Yellow
}
else {
    Write-Host "[finalize] .sln already clean" -ForegroundColor DarkGray
}

# delete leftover helper project files / intermediate dirs
$deleted = 0
foreach ($name in $helperNames) {
    $items = Get-ChildItem -LiteralPath $buildDir -Recurse -Force -ErrorAction SilentlyContinue |
        Where-Object {
            ($_.Name -like "$name.vcxproj*") -or
            ($_.PSIsContainer -and ($_.Name -eq "$name.dir" -or $_.Name -eq $name))
        }
    foreach ($it in $items) {
        Remove-Item -LiteralPath $it.FullName -Recurse -Force -ErrorAction SilentlyContinue
        $deleted++
    }
}
if ($deleted -gt 0) { Write-Host "[finalize] deleted $deleted helper file(s)/dir(s)" -ForegroundColor DarkGray }

# drop stale Visual Studio user state: it caches the startup project, and if
# that cache still points at ALL_BUILD the first F5 fails ("cannot find exe").
$vsState = @()
$vsState += Get-ChildItem -LiteralPath $buildDir -Force -Directory -Filter '.vs' -ErrorAction SilentlyContinue
$vsState += Get-ChildItem -LiteralPath $buildDir -Force -Recurse -Filter '*.suo' -ErrorAction SilentlyContinue
foreach ($s in $vsState) {
    Remove-Item -LiteralPath $s.FullName -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host "[finalize] cleared stale VS state: $($s.Name)" -ForegroundColor DarkGray
}

# ===========================================================================
# 2. make the generated project files use relative paths
# ===========================================================================
$projFiles = Get-ChildItem -LiteralPath $buildDir -File -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -like '*.vcxproj' -or $_.Name -like '*.vcxproj.filters' -or $_.Name -like '*.vcxproj.user' }
if ($projFiles.Count -eq 0) { Write-Host "[finalize] no project files found"; exit 0 }

# source directory = directory of the first ClCompile item in the main vcxproj
$mainProj = $projFiles | Where-Object { $_.Name -like '*.vcxproj' } | Select-Object -First 1
$mainText = [System.IO.File]::ReadAllText($mainProj.FullName, [System.Text.Encoding]::UTF8)
$srcDir = $null
$m = [regex]::Match($mainText, 'ClCompile Include="([^"]+)"')
if ($m.Success) {
    $inc = $m.Groups[1].Value
    if ([System.IO.Path]::IsPathRooted($inc)) {
        $srcDir = Split-Path -Parent $inc
    }
}
if (-not $srcDir) {
    # build dir is normally <root>\build
    $srcDir = Split-Path -Parent $buildDir
}
$srcDir = [System.IO.Path]::GetFullPath($srcDir)
$buildDirAbs = [System.IO.Path]::GetFullPath($buildDir)

# Windows PowerShell 5.1 has no [System.IO.Path]::GetRelativePath, compute it.
function Get-RelPath([string]$fromDir, [string]$toDir) {
    $fp = ([System.IO.Path]::GetFullPath($fromDir).TrimEnd('\', '/')) -split '[\\/]'
    $tp = ([System.IO.Path]::GetFullPath($toDir).TrimEnd('\', '/')) -split '[\\/]'
    $i = 0
    while ($i -lt $fp.Count -and $i -lt $tp.Count -and ($fp[$i] -ieq $tp[$i])) { $i++ }
    $parts = New-Object System.Collections.Generic.List[string]
    for ($k = $i; $k -lt $fp.Count; $k++) { $parts.Add('..') }
    for ($k = $i; $k -lt $tp.Count; $k++) { $parts.Add($tp[$k]) }
    if ($parts.Count -eq 0) { return '.' }
    return ($parts -join '\')
}

$relBack = Get-RelPath $buildDirAbs $srcDir   # e.g. ".." or "..\.."
$relBs = $relBack + '\'
$relFs = ($relBack -replace '\\', '/') + '/'
$bAbsBs = $buildDirAbs + '\'
$bAbsFs = ($buildDirAbs -replace '\\', '/') + '/'
$sAbsBs = $srcDir + '\'
$sAbsFs = ($srcDir -replace '\\', '/') + '/'

$changed = 0
foreach ($f in $projFiles) {
    $t = [System.IO.File]::ReadAllText($f.FullName, [System.Text.Encoding]::UTF8)
    $orig = $t

    # (a) item paths (Include="...") -> plain relative to the project dir
    $t = $t.Replace('Include="' + $sAbsBs, 'Include="' + $relBs)
    $t = $t.Replace('Include="' + $sAbsFs, 'Include="' + $relFs)

    # (b) property values (OutDir / ImportLibrary / ProgramDataBaseFile / ...)
    #     -> $(ProjectDir)-rooted, NOT a bare relative path.
    #     A bare "Debug\" would leave $(TargetPath) relative, and the VS
    #     debugger would then fail with "cannot find the file ... SPH.exe".
    #     $(ProjectDir) is still not an absolute path in the file, but it
    #     expands to an absolute one, which is what the debugger needs.
    $t = $t.Replace($bAbsBs, '$(ProjectDir)').Replace($bAbsFs, '$(ProjectDir)')
    $t = $t.Replace($sAbsBs, '$(ProjectDir)' + $relBs).Replace($sAbsFs, '$(ProjectDir)' + $relFs)

    # (c) unpin the Windows SDK version.
    #     CMake writes the concrete SDK of the machine that configured, e.g.
    #     <WindowsTargetPlatformVersion>10.0.26100.0</...>.  On a machine that
    #     does not have exactly that SDK, $(WindowsSDK_IncludePath) stays
    #     empty and the compiler reports
    #         C1083: cannot open include file: 'ctype.h'
    #     "10.0" means "newest installed Windows 10/11 SDK" and is portable.
    $t = [regex]::Replace($t,
        '<WindowsTargetPlatformVersion>[^<]*</WindowsTargetPlatformVersion>',
        '<WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>')

    if ($t -ne $orig) {
        [System.IO.File]::WriteAllText($f.FullName, $t, (New-Object System.Text.UTF8Encoding($true)))
        $changed++
        Write-Host "[finalize] relativized: $($f.Name)" -ForegroundColor DarkGray
    }
}

# report anything still absolute
$still = @()
foreach ($f in $projFiles) {
    $t = [System.IO.File]::ReadAllText($f.FullName, [System.Text.Encoding]::UTF8)
    foreach ($mm in [regex]::Matches($t, '(?<![A-Za-z])[A-Za-z]:[\\/][^"<>]*')) { $still += $mm.Value }
}
if ($still.Count -eq 0) {
    Write-Host "[finalize] no absolute paths left in project files" -ForegroundColor Green
}
else {
    Write-Host "[finalize] WARNING: $($still.Count) absolute path(s) still present:" -ForegroundColor Yellow
    $still | Sort-Object -Unique | Select-Object -First 10 | ForEach-Object { Write-Host "    $_" }
}
Write-Host "[finalize] done ($changed file(s) rewritten)"
